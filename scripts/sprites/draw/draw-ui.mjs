// Gear and code are built from shapes so the strokes stay even.
{
  const gear = Array.from({ length: 16 }, () => Array(16).fill('.'))
  const d = (x, y) => Math.hypot(x + 0.5 - 8, y + 0.5 - 8)
  for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
    const r = d(x, y)
    const tooth = (Math.abs(x + 0.5 - 8) <= 1.5 && r <= 7.6) || (Math.abs(y + 0.5 - 8) <= 1.5 && r <= 7.6) ||
      (Math.abs(Math.abs(x + 0.5 - 8) - Math.abs(y + 0.5 - 8)) <= 1.2 && r <= 7.6 && r >= 5)
    if ((r <= 5.6 || tooth) && r > 2.4) gear[y][x] = '#'
  }
  GLYPHS.gear = gear.map((r) => r.join(''))
  const code = Array.from({ length: 16 }, () => Array(16).fill('.'))
  const line = (x0, y0, x1, y1) => {
    const n = Math.max(Math.abs(x1 - x0), Math.abs(y1 - y0))
    for (let i = 0; i <= n; i++) {
      const x = Math.round(x0 + ((x1 - x0) * i) / n), y = Math.round(y0 + ((y1 - y0) * i) / n)
      code[y][x] = '#'; code[y][x + 1] = '#'
    }
  }
  line(5, 3, 1, 7); line(1, 8, 5, 12)
  line(9, 3, 13, 7); line(13, 8, 9, 12)
  line(9, 1, 6, 14)
  GLYPHS.code = code.map((r) => r.slice(0, 16).join(''))
}
// Fix a few glyphs that need exact 16-wide rows (trim stray spaces).
for (const k of Object.keys(GLYPHS)) GLYPHS[k] = GLYPHS[k].map((r) => r.replace(/ /g, '.').slice(0, 16).padEnd(16, '.'))

function glyphGrid(name, ink) {
  const g = grid(16, 16)
  paste(g, GLYPHS[name], 0, 0, { '#': ink, o: '#E0832A', g: '#5E8A3A' })
  if (name === 'pumpkin') {
    // outline the pumpkin body and add a highlight and shade
    const src = grid(16, 16)
    paste(src, GLYPHS[name], 0, 0, { '#': ink, o: '#E0832A', g: '#5E8A3A' })
    for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) {
      const c = at(src, x, y)
      if (c === '#E0832A') {
        if (x === 3 && y >= 5 && y <= 8) put(g, x, y, '#F2A64E')
        if (y >= 12 || x >= 13) put(g, x, y, '#BA6420')
      }
      if (!c) {
        const near = [[1, 0], [-1, 0], [0, 1], [0, -1]].some(([dx, dy]) => ['#E0832A', '#5E8A3A'].includes(at(src, x + dx, y + dy)))
        if (near) put(g, x, y, ink)
      }
    }
  }
  return g
}
