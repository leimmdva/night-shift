// ---------- grid helpers ----------
const grid = (w, h) => ({ w, h, p: Array.from({ length: h }, () => Array(w).fill(null)) })
const put = (g, x, y, c) => { if (x >= 0 && y >= 0 && x < g.w && y < g.h) g.p[y][x] = c }
const at = (g, x, y) => (x >= 0 && y >= 0 && x < g.w && y < g.h ? g.p[y][x] : null)

// Mask of a rectangle with stepped corners. Each corner is an array of row insets, e.g. [2, 1].
function shape(w, h, { tl = [], tr = [], bl = [], br = [] } = {}) {
  const m = Array.from({ length: h }, () => Array(w).fill(false))
  for (let y = 0; y < h; y++) {
    const top = y, bot = h - 1 - y
    const l = Math.max(tl[top] ?? 0, bl[bot] ?? 0)
    const r = Math.max(tr[top] ?? 0, br[bot] ?? 0)
    for (let x = l; x < w - r; x++) m[y][x] = true
  }
  return m
}
const inM = (m, x, y) => y >= 0 && y < m.length && x >= 0 && x < m[0].length && m[y][x]

// Beveled, outlined box. pal = { f, hi, sh }. mode 'raised' | 'pressed'.
function bevel(w, h, pal, corners, { ink = INK, mode = 'raised', shadowRows = 2, g = grid(w, h) } = {}) {
  const m = shape(w, h, corners)
  const edge = (x, y) => inM(m, x, y) && !(inM(m, x - 1, y) && inM(m, x + 1, y) && inM(m, x, y - 1) && inM(m, x, y + 1))
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    if (!inM(m, x, y)) continue
    if (edge(x, y)) { put(g, x, y, ink); continue }
    const up = edge(x, y - 1), left = edge(x - 1, y)
    let down = false
    for (let k = 1; k <= shadowRows; k++) if (edge(x, y + k)) down = true
    const right = edge(x + 1, y)
    let c = pal.f
    if (mode === 'raised') { if (up || left) c = pal.hi; else if (down || right) c = pal.sh }
    else { if (up || left) c = pal.sh }
    put(g, x, y, c)
  }
  return g
}

function paste(g, rows, ox, oy, map) {
  rows.forEach((row, y) => [...row].forEach((ch, x) => { if (map[ch]) put(g, ox + x, oy + y, map[ch]) }))
}
function circle(g, cx, cy, r, c) {
  for (let y = 0; y < g.h; y++) for (let x = 0; x < g.w; x++) if ((x + 0.5 - cx) ** 2 + (y + 0.5 - cy) ** 2 <= r * r) put(g, x, y, c)
}

// ---------- output ----------
const meta = []
function emit(name, g, info = {}) {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
  const legend = new Map()
  for (const row of g.p) for (const c of row) if (c && !legend.has(c)) legend.set(c, chars[legend.size])
  if (legend.size > chars.length) throw new Error(`${name}: too many colours`)
  const head = [`# ${name} (${g.w}x${g.h})`, "# Generated by scripts/sprites/draw/draw-ui.mjs. '.' = transparent; every other character is one pixel."]
  for (const [k, v] of Object.entries(info)) head.push(`# meta ${k}=${Array.isArray(v) ? v.join(',') : v}`)
  for (const [c, ch] of legend) head.push(`@ ${ch} ${c}`)
  const body = g.p.map((row) => row.map((c) => (c ? legend.get(c) : '.')).join(''))
  writeFileSync(join(OUT, `${name}.txt`), [...head, '---', ...body, ''].join('\n'))
  meta.push(name)
}

